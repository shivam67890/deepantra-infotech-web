// Helper: Fisher-Yates array shuffle
export function shuffleArray(arr) {
  const copy = [...arr];
  for (let i = copy.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy;
}

// Generate a randomized quiz from the question bank matching topics, grades, and count
export function generateRandomQuiz({ topic = 'all', difficulty = 'all', grade = null, count = 5 } = {}) {
  // 1. Filter by topic
  let topicPool = QUESTION_BANK;
  if (topic && topic !== 'all') {
    topicPool = QUESTION_BANK.filter((q) => q.topic === topic);
  }

  // 2. Filter by Grade or Difficulty
  let filtered = topicPool;
  if (grade) {
    const targetGrade = Number(grade);
    const gradeMatches = topicPool.filter((q) => q.gradeLevels && q.gradeLevels.includes(targetGrade));
    if (gradeMatches.length > 0) {
      filtered = gradeMatches;
    }
  } else if (difficulty && difficulty !== 'all') {
    const diffMatches = topicPool.filter((q) => q.difficulty === difficulty);
    if (diffMatches.length > 0) {
      filtered = diffMatches;
    }
  }

  // 3. Ensure we have enough questions to fulfill the count
  // If the filtered pool has fewer questions than requested count, gracefully backfill from the rest of the topic pool
  let finalPool = filtered;
  if (filtered.length < count) {
    const remaining = topicPool.filter((q) => !filtered.some((f) => f.id === q.id));
    finalPool = [...filtered, ...shuffleArray(remaining)];
  }

  // 4. Shuffle the selected pool
  const shuffledQuestions = shuffleArray(finalPool);

  // 5. Slice requested count
  const selected = shuffledQuestions.slice(0, Math.min(count, shuffledQuestions.length));

  // 6. Shuffle options for each selected question so the correct answer isn't predictable
  return selected.map((q, idx) => {
    const originalCorrectOption = q.options[q.correctIndex];
    const shuffledOptions = shuffleArray(q.options);
    const newCorrectIndex = shuffledOptions.indexOf(originalCorrectOption);

    return {
      ...q,
      quizIndex: idx + 1,
      options: shuffledOptions,
      correctIndex: newCorrectIndex,
    };
  });
}
